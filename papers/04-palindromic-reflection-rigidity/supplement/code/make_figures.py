# Figure 2: twins and ladders.

EXCHANGE = {"ab": "ba", "ba": "ab"}


def label_root(word):
    a11, a12, a21, a22 = 1, 0, 0, 1
    for letter in word:
        if letter == "a":
            a11, a12, a21, a22 = 2 * a11 + a12, a11 + a12, 2 * a21 + a22, a21 + a22
        else:
            a11, a12, a21, a22 = 5 * a11 + 2 * a12, 2 * a11 + a12, 5 * a21 + 2 * a22, 2 * a21 + a22
    x, y = 2 * a11 + a12, 2 * a21 + a22
    return 2 * x + y, x


def palindromes(bound):
    stack = [("", 2, 1)]
    while stack:
        w, x, y = stack.pop()
        even = x * x + y * y
        if even > bound:
            continue
        rw = w[::-1]
        for label, z in ((even, rw + w), (2 * x * x + 2 * x * y + y * y, rw + "a" + w),
                         (5 * x * x + 4 * x * y + y * y, rw + "b" + w)):
            if label <= bound:
                yield z
        stack.append(("a" + w, 2 * x + y, x + y))
        stack.append(("b" + w, 5 * x + 2 * y, 2 * x + y))


def pal(directive):
    """Iterated right palindromic closure, from the definition."""
    word = ""
    for letter in directive:
        word += letter
        for i in range(len(word) + 1):
            if word[i:] == word[i:][::-1]:
                word += word[:i][::-1]
                break
    return word


def central_words(bound):
    """All central words Pal(d) with label at most bound.

    Pal(d) is a proper prefix of Pal(dc), and a proper extension has a strictly
    larger label, so the search over directives can stop at the bound.
    """
    found, stack = set(), [""]
    while stack:
        d = stack.pop()
        z = pal(d)
        if label_root(z)[0] > bound:
            continue
        found.add(z)
        stack.extend((d + "a", d + "b"))
    return found


def exchange_partners(z):
    for length in range(len(z) - 1):
        p = z[:length]
        if p != p[::-1]:
            continue
        i, blocks = len(p), []
        while i < len(z):
            block = z[i:i + 2]
            if block not in EXCHANGE:
                break
            blocks.append(block)
            i += 2
            if z[i:i + len(p)] != p:
                break
            i += len(p)
        else:
            if len(blocks) >= 2:
                yield p, p + "".join(EXCHANGE[b] + p for b in blocks)


def ladder_figure(bound=10**12):
    words = list(palindromes(bound))
    data = {}
    by_label = defaultdict(list)
    for z in words:
        m, r = label_root(z)
        data[z] = (m, Fraction(r, m))
        by_label[m].append(z)
    rungs, feet = set(), set()
    for m, group in by_label.items():
        if len(group) < 2:
            continue
        for z in group:
            for p, partner in exchange_partners(z):
                assert partner in group
                rungs.add((m, tuple(sorted((z, partner))), p))
                feet.add(p)
    twins = {z for m, g in by_label.items() if len(g) > 1 for z in g}
    central = central_words(bound)
    assert central <= set(words)
    assert not (twins & central)

    smin, smax = (3 - math.sqrt(5)) / 2, math.sqrt(2) - 1
    width, height = 12.4, 7.0
    ymin, ymax = 0.5, 12.25

    def px(s):
        return (float(s) - smin) / (smax - smin) * width

    def py(m):
        return (math.log10(m) - ymin) / (ymax - ymin) * height

    out = [HEADER, r"\begin{tikzpicture}[font=\footnotesize]"]
    # frame: left and bottom spines, ticks outward
    out.append(rf"\draw[ink, line width=0.5pt] (0,{fmt(height)}) -- (0,0) -- ({fmt(width)},0);")
    for e in range(0, 13, 3):
        y = py(10 ** e) if e > 0 else py(1) if ymin <= 0 else None
        if y is None or y < 0:
            continue
        out.append(rf"\draw[ink, line width=0.5pt] (0,{fmt(y)}) -- (-0.08,{fmt(y)});")
        out.append(rf"\node[ink, left] at (-0.08,{fmt(y)}) {{$10^{{{e}}}$}};")
    for s in (0.385, 0.39, 0.395, 0.4, 0.405, 0.41):
        out.append(rf"\draw[ink, line width=0.5pt] ({fmt(px(s))},0) -- ({fmt(px(s))},-0.08);")
        out.append(rf"\node[ink, below] at ({fmt(px(s))},-0.08) {{${s:.3f}$}};")
    out.append(rf"\node[ink, below] at ({fmt(width / 2)},-0.48) {{$\rho(z)/M(z)$, the frequency of $b$ in $\Omega_z$}};")
    out.append(rf"\node[ink, rotate=90, above] at (-0.75,{fmt(height / 2)}) {{Gram label $M(z)$}};")
    # other palindromes, then central words
    for z in words:
        if z in twins or z in central:
            continue
        m, s = data[z]
        out.append(rf"\fill[slate] ({fmt(px(s))},{fmt(py(m))}) circle (0.28pt);")
    for z in sorted(central):
        m, s = data[z]
        out.append(rf"\fill[navy] ({fmt(px(s))},{fmt(py(m))}) circle (0.75pt);")
    # posts and rungs
    for m, (z1, z2), p in sorted(rungs):
        mp, sp = data[p] if p in data else label_root(p)
        out.append(rf"\draw[slate, densely dotted, line width=0.35pt] ({fmt(px(sp))},{fmt(py(mp))}) -- ({fmt(px(sp))},{fmt(py(m))});")
    for m, (z1, z2), p in sorted(rungs):
        s1, s2 = data[z1][1], data[z2][1]
        out.append(rf"\draw[wine, line width=0.7pt] ({fmt(px(s1))},{fmt(py(m))}) -- ({fmt(px(s2))},{fmt(py(m))});")
    for z in sorted(twins):
        m, s = data[z]
        out.append(rf"\draw[wine, fill=white, line width=0.45pt] ({fmt(px(s))},{fmt(py(m))}) circle (1.1pt);")
    for p in sorted(feet):
        m, s = data[p]
        out.append(rf"\filldraw[ochre, draw=ink, line width=0.25pt] ({fmt(px(s))},{fmt(py(m))}) +(0,1.9pt) -- +(1.9pt,0) -- +(0,-1.9pt) -- +(-1.9pt,0) -- cycle;")
        if p in twins:
            # a twin that is also a centre: ring the diamond so that both roles show
            out.append(rf"\draw[wine, line width=0.45pt] ({fmt(px(s))},{fmt(py(m))}) circle (2.7pt);")
    # labels of the three lowest centres, in empty space beside their diamonds
    for word, name, side in (("", r"$\varepsilon$", "right"), ("a", r"$a$", "right"), ("b", r"$b$", "left")):
        m, s = data[word]
        out.append(rf"\node[ink, {side}=2.2pt] at ({fmt(px(s))},{fmt(py(m))}) {{{name}}};")
    # legend above the plot, outside the data
    ly = height + 0.42
    out.append(rf"\fill[navy] (0.2,{fmt(ly)}) circle (0.75pt); \node[ink, right] at (0.28,{fmt(ly)}) {{central word}};")
    out.append(rf"\filldraw[ochre, draw=ink, line width=0.25pt] (2.6,{fmt(ly)}) +(0,1.9pt) -- +(1.9pt,0) -- +(0,-1.9pt) -- +(-1.9pt,0) -- cycle; \node[ink, right] at (2.7,{fmt(ly)}) {{centre $p$}};")
    out.append(rf"\draw[wine, line width=0.7pt] (4.5,{fmt(ly)}) -- (5.1,{fmt(ly)}); \draw[wine, fill=white, line width=0.45pt] (4.5,{fmt(ly)}) circle (1.1pt) (5.1,{fmt(ly)}) circle (1.1pt); \node[ink, right] at (5.2,{fmt(ly)}) {{twins and their rung}};")
    out.append(rf"\fill[slate] (8.85,{fmt(ly)}) circle (0.5pt); \node[ink, right] at (8.93,{fmt(ly)}) {{other palindrome}};")
    out.append(r"\end{tikzpicture}")
    stats = dict(palindromes=len(words), central=len(central), twins=len(twins),
                 rungs=len(rungs), feet=sorted(feet, key=lambda p: data[p][0]))
    return "\n".join(out) + "\n", stats


