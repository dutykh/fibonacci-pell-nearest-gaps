"""Write the TikZ code of the three figures of the article from exact data.

``figures/cusp-cylinders.tex``: the cusp coordinate at the empty directive, with
the two rays of the orbit set, the poles of the first-letter maps, their four
distances to the rays and the two cylinders, with the columns of all words of
length at most nine.

``figures/twin-ladders.tex``: every palindrome with label at most ``10^12`` in
the plane of the ratio rho/M and the label; central words, twins joined by the rungs of their
block exchanges, and the centres of those exchanges.

``figures/nested-square.tex``: the first square of nested exchanges, at the label
12 986 074 130, with the rung below it and the midpoints of its two diagonals.

All arithmetic is exact (integers and fractions); coordinates are rounded to
three decimals of a centimetre only when written.  Run from the article folder:

    python3 -B supplement/code/make_figures.py
"""

