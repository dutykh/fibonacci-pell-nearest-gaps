# Figure 1: the cusp coordinate at the empty directive.

def cusp_figure():
    scale = 1.98                       # centimetres per unit of z
    zmin, zmax = -3.95, 3.05

    def x(z):
        return (float(z) - zmin) * scale

    def f(z):                          # letter a: f(z) = -3 - 1/z
        return Fraction(-3) if z is None else -3 - 1 / z

    def g(z):                          # letter b: g(z) = 5/2 - 1/(4z + 2)
        return Fraction(5, 2) if z is None else Fraction(5, 2) - 1 / (4 * z + 2)

    points = {None}
    frontier = {None}
    for _ in range(9):
        frontier = {f(z) for z in frontier} | {g(z) for z in frontier}
        points |= frontier
    finite = sorted(z for z in points if z is not None)
    ticks = sorted({round(x(z), 3) for z in finite})

    u_box = (Fraction(-41, 12), Fraction(-3) + Fraction(12, 25))
    v_box = (Fraction(5, 2) - Fraction(10, 111), Fraction(21, 8))
    assert all(u_box[0] <= z <= u_box[1] or v_box[0] <= z <= v_box[1] for z in finite)

    lines = [HEADER, r"\begin{tikzpicture}[font=\footnotesize, >={Stealth[length=4pt]}]"]
    y_f, y_g = -0.78, -1.42
    # guides from the ends of the rays down to the distance arrows
    for z in (Fraction(-5, 2), Fraction(12, 5)):
        lines.append(rf"\draw[mist, densely dotted, line width=0.5pt] ({fmt(x(z))},-0.56) -- ({fmt(x(z))},{y_g - 0.12});")
    # the axis: gap thin, rays thick, both ends towards the point at infinity
    lines.append(rf"\draw[mist, line width=0.8pt] ({fmt(x(Fraction(-5, 2)))},0) -- ({fmt(x(Fraction(12, 5)))},0);")
    lines.append(rf"\draw[navy, line width=2.2pt] ({fmt(x(Fraction(-5, 2)))},0) -- ({fmt(x(zmin) + 0.15)},0);")
    lines.append(rf"\draw[navy, line width=2.2pt] ({fmt(x(Fraction(12, 5)))},0) -- ({fmt(x(zmax) - 0.15)},0);")
    lines.append(rf"\draw[navy, ->, line width=0.8pt] ({fmt(x(zmin) + 0.2)},0) -- ({fmt(x(zmin) - 0.05)},0);")
    lines.append(rf"\draw[navy, ->, line width=0.8pt] ({fmt(x(zmax) - 0.2)},0) -- ({fmt(x(zmax) + 0.05)},0);")
    lines.append(rf"\node[ink, below] at ({fmt(x(zmin))},-0.08) {{$\infty$}};")
    lines.append(rf"\node[ink, below] at ({fmt(x(zmax))},-0.08) {{$\infty$}};")
    lines.append(rf"\node[ink, below] at ({fmt(x(Fraction(-5, 2)))},-0.08) {{$-5/2$}};")
    lines.append(rf"\node[ink, below] at ({fmt(x(Fraction(12, 5)))},-0.08) {{$12/5$}};")
    lines.append(rf"\node[ink, below] at ({fmt(x(0))},-0.08) {{$0$}};")
    lines.append(rf"\draw[ink, line width=0.5pt] ({fmt(x(0))},-0.07) -- ({fmt(x(0))},0.07);")
    # the cylinders and the orbit points
    for (lo, hi), name in ((u_box, r"\mathcal U"), (v_box, r"\mathcal V")):
        lines.append(rf"\filldraw[fill=sand, draw=ink, line width=0.4pt] ({fmt(x(lo))},0.16) rectangle ({fmt(x(hi))},0.58);")
        lines.append(rf"\node[ink, above] at ({fmt((x(lo) + x(hi)) / 2)},0.6) {{${name}$}};")
    for t in ticks:
        lines.append(rf"\draw[navy, line width=0.25pt] ({fmt(t)},0.2) -- ({fmt(t)},0.54);")
    # the ranges of the poles and the four distances
    rows = (
        (y_f, Fraction(-5, 12), Fraction(0), "wine", r"pole of $f$", "25/12", "12/5"),
        (y_g, Fraction(-1, 2), Fraction(-3, 8), "teal", r"pole of $g$", "2", "111/40"),
    )
    for y, lo, hi, colour, name, left, right in rows:
        lines.append(rf"\draw[{colour}, <->, line width=0.6pt] ({fmt(x(-Fraction(5, 2)))},{y}) -- ({fmt(x(lo))},{y});")
        lines.append(rf"\draw[{colour}, <->, line width=0.6pt] ({fmt(x(hi))},{y}) -- ({fmt(x(Fraction(12, 5)))},{y});")
        lines.append(rf"\draw[{colour}, line width=3pt] ({fmt(x(lo))},{y}) -- ({fmt(x(hi))},{y});")
        lines.append(rf"\node[{colour}, above] at ({fmt((x(-Fraction(5, 2)) + x(lo)) / 2)},{y}) {{${left}$}};")
        lines.append(rf"\node[{colour}, above] at ({fmt((x(hi) + x(Fraction(12, 5))) / 2)},{y}) {{${right}$}};")
        lines.append(rf"\node[{colour}, below] at ({fmt((x(lo) + x(hi)) / 2)},{y - 0.04}) {{{name}}};")
    lines.append(r"\end{tikzpicture}")
    return "\n".join(lines) + "\n", len(finite)


