# Figure 3: the first square of nested exchanges.

def nested_square_figure():
    """The square of Corollary cor:nested-square for p empty and W = V = (ba, ab).

    The two lower levels are drawn to scale in the ratio rho/M.  At the top level each
    twin sits at a centre ratio plus or minus 3/N, N = 9*1130^2 + 1; these offsets are
    about 2.6e-7 and are drawn as a fixed visible distance, the same for every offset,
    so that the drawing keeps the exact geometry of the reflections.
    """
    def angle(q, blocks):
        return q + "".join(b + q for b in blocks)

    w = ["ba", "ab"]
    p1, p2 = angle("", w), angle("", [EXCHANGE[b] for b in w])
    z = [angle(p1, w), angle(p1, [EXCHANGE[b] for b in w]),
         angle(p2, w), angle(p2, [EXCHANGE[b] for b in w])]
    assert (p1, p2) == ("baab", "abba")
    assert z == ["baabbabaababbaab", "baababbaabbabaab", "abbabaabbaababba", "abbaababbabaabba"]
    m0, r0 = label_root("")
    m1, r1 = label_root(p1)
    m2, r2 = label_root(p2)
    data = [label_root(x) for x in z]
    m = data[0][0]
    n = 9 * m1 * m1 + 1
    assert (m0, r0, m1, r1, m2, r2) == (5, 2, 1130, 467, 1130, 437)
    assert all(d[0] == m for d in data) and m == m1 * n == 12986074130 and n == 11492101
    rho = [d[1] for d in data]
    assert rho == [r1 * n + 3 * m1, r1 * n - 3 * m1, r2 * n + 3 * m1, r2 * n - 3 * m1]
    c0, c1, c2 = Fraction(r0, m0), Fraction(r1, m1), Fraction(r2, m2)
    assert c1 + c2 == 2 * c0
    shift = Fraction(3, n)
    assert Fraction(rho[0] + rho[2], 2 * m) == c0 + shift and Fraction(rho[1] + rho[3], 2 * m) == c0 - shift
    assert Fraction(rho[0] + rho[1], 2 * m) == c1 and Fraction(rho[2] + rho[3], 2 * m) == c2
    assert Fraction(rho[0] + rho[3], 2 * m) == c0 and Fraction(rho[1] + rho[2], 2 * m) == c0

    smin, smax, width = 0.380, 0.420, 10.8
    d = 0.55                                    # drawn length of one offset 3/N

    def px(s):
        return (float(s) - smin) / (smax - smin) * width

    y0, y1, y2 = 0.55, 2.35, 4.75
    x0, x1, x2 = px(c0), px(c1), px(c2)
    top = {1: x1 + d, 2: x1 - d, 3: x2 + d, 4: x2 - d}   # Z_1..Z_4, sign of the offset as in rho
    assert abs((top[1] + top[4]) / 2 - x0) < 1e-9 and abs((top[2] + top[3]) / 2 - x0) < 1e-9

    def diamond(x, y, ringed=False):
        s = rf"\filldraw[ochre, draw=ink, line width=0.25pt] ({fmt(x)},{fmt(y)}) +(0,1.9pt) -- +(1.9pt,0) -- +(0,-1.9pt) -- +(-1.9pt,0) -- cycle;"
        if ringed:
            s += rf" \draw[wine, line width=0.45pt] ({fmt(x)},{fmt(y)}) circle (2.7pt);"
        return s

    out = [HEADER, r"\begin{tikzpicture}[font=\footnotesize]"]
    # ratio axis, to scale for the two lower levels
    out.append(rf"\draw[ink, line width=0.5pt] (0,0) -- ({fmt(width)},0);")
    for s in (0.385, 0.39, 0.395, 0.4, 0.405, 0.41, 0.415):
        out.append(rf"\draw[ink, line width=0.5pt] ({fmt(px(s))},0) -- ({fmt(px(s))},-0.08);")
        out.append(rf"\node[ink, below] at ({fmt(px(s))},-0.08) {{${s:.3f}$}};")
    out.append(rf"\node[ink, below] at ({fmt(width / 2)},-0.48) {{$\rho/M$}};")
    # level labels, left of the data
    for y, text in ((y0, r"$M=5$"), (y1, r"$M=1130$"), (y2, r"$M=12\,986\,074\,130$")):
        out.append(rf"\node[ink, left] at (-0.1,{fmt(y)}) {{{text}}};")
    # posts: the centre of every rung above its centre
    out.append(rf"\draw[slate, densely dotted, line width=0.4pt] ({fmt(x0)},{fmt(y0)}) -- ({fmt(x0)},{fmt(y2)});")
    out.append(rf"\draw[slate, densely dotted, line width=0.4pt] ({fmt(x1)},{fmt(y1)}) -- ({fmt(x1)},{fmt(y2)});")
    out.append(rf"\draw[slate, densely dotted, line width=0.4pt] ({fmt(x2)},{fmt(y1)}) -- ({fmt(x2)},{fmt(y2)});")
    # the lower rung, abba -- baab, around the empty word
    out.append(rf"\draw[navy, line width=0.8pt] ({fmt(x2)},{fmt(y1)}) -- ({fmt(x1)},{fmt(y1)});")
    # the exchanges around the empty word at the top level: two nested arcs above the row
    for (i, j), h in (((2, 3), 0.75), ((1, 4), 1.15)):
        a, b = top[j], top[i]
        out.append(rf"\draw[navy, line width=0.8pt] ({fmt(a)},{fmt(y2)}) .. controls ({fmt(a)},{fmt(y2 + h)}) and ({fmt(b)},{fmt(y2 + h)}) .. ({fmt(b)},{fmt(y2)});")
    # the short rungs, around baab and abba
    out.append(rf"\draw[wine, line width=0.9pt] ({fmt(top[2])},{fmt(y2)}) -- ({fmt(top[1])},{fmt(y2)});")
    out.append(rf"\draw[wine, line width=0.9pt] ({fmt(top[4])},{fmt(y2)}) -- ({fmt(top[3])},{fmt(y2)});")
    # the midpoints of the two diagonals, just below the row
    for x in (x0 - d, x0 + d):
        out.append(rf"\draw[ochre, fill=white, line width=0.6pt] ({fmt(x)},{fmt(y2 - 0.32)}) circle (1.5pt);")
    # annotation between the two upper levels, left of the centre post and right of the abba post
    tx, ty, tw = x2 + 0.32, (y1 + y2) / 2 - 0.12, 2.85
    assert x2 + 0.25 < tx and tx + tw < x0 - 0.15
    out.append(rf"\draw[slate, line width=0.35pt] ({fmt(x0 - d - 0.05)},{fmt(y2 - 0.38)}) -- ({fmt(tx + tw - 0.55)},{fmt(ty + 0.7)});")
    out.append(rf"\node[ink, right, align=left, inner sep=1pt] at ({fmt(tx)},{fmt(ty)}) {{midpoints $2/5\pm3/N$\\of the diagonals\\$(Z_1,Z_3)$ and $(Z_2,Z_4)$}};")
    # the four twins and their names
    for k, x in sorted(top.items()):
        out.append(rf"\draw[wine, fill=white, line width=0.45pt] ({fmt(x)},{fmt(y2)}) circle (1.3pt);")
        out.append(rf"\node[ink, below] at ({fmt(x)},{fmt(y2 - 0.06)}) {{$Z_{k}$}};")
    # the centres
    out.append(diamond(x0, y0))
    out.append(rf"\node[ink, right=2.2pt] at ({fmt(x0)},{fmt(y0)}) {{$\varepsilon$}};")
    out.append(diamond(x1, y1, ringed=True))
    out.append(rf"\node[ink, below right=1pt] at ({fmt(x1)},{fmt(y1)}) {{$baab$}};")
    out.append(diamond(x2, y1, ringed=True))
    out.append(rf"\node[ink, below left=1pt] at ({fmt(x2)},{fmt(y1)}) {{$abba$}};")
    # legend above the data, two rows
    la, lb = y2 + 2.05, y2 + 1.6
    out.append(rf"\draw[navy, line width=0.8pt] (0.2,{fmt(la)}) -- (0.8,{fmt(la)}); \node[ink, right] at (0.85,{fmt(la)}) {{exchange around $\varepsilon$}};")
    out.append(rf"\draw[wine, line width=0.9pt] (4.6,{fmt(la)}) -- (5.2,{fmt(la)}); \node[ink, right] at (5.25,{fmt(la)}) {{exchange around $baab$ or $abba$}};")
    out.append(diamond(0.5, lb) + rf" \node[ink, right] at (0.85,{fmt(lb)}) {{centre of an exchange}};")
    out.append(rf"\draw[ochre, fill=white, line width=0.6pt] (4.9,{fmt(lb)}) circle (1.5pt); \node[ink, right] at (5.25,{fmt(lb)}) {{midpoint of a diagonal}};")
    out.append(r"\end{tikzpicture}")
    return "\n".join(out) + "\n", dict(label=m, n=n)


def main():
    if len(sys.argv) != 1:
        raise SystemExit("This fixed generator accepts no arguments.")
    text, count = cusp_figure()
    (ROOT / "figures" / "cusp-cylinders.tex").write_text(text)
    print(f"figures/cusp-cylinders.tex: {count} orbit points of words of length at most nine")
    text, stats = ladder_figure()
    (ROOT / "figures" / "twin-ladders.tex").write_text(text)
    print(f"figures/twin-ladders.tex: {stats['palindromes']} palindromes, {stats['central']} central,"
          f" {stats['twins']} twins, {stats['rungs']} rungs, centres {stats['feet']}")
    text, info = nested_square_figure()
