    lines.append(rf"\draw[wine, line width=0.6pt, fill=none] ({fmt(X(root))},{fmt(Y(least))}) circle (3.2pt);")
    lines.append(rf"\draw[ink, line width=0.5pt] ({fmt(x0)},0) -- ({fmt(w)},0);")
    lines.append(rf"\draw[ink, line width=0.5pt] ({fmt(x0)},0) -- ({fmt(x0)},{fmt(h)});")
