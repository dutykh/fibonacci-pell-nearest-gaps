# Figure: the Euclidean costs of the pairs (n, m) for one label.

def continued_fraction(p, q):
    out = []
    while q:
        out.append(p // q)
        p, q = q, p % q
    return out


def block_form(c):
    """True when c = [2; B_1, ..., B_j, 2] with every block B_i equal to (2) or (1, 1)."""
    if len(c) < 2 or c[0] != 2 or c[-1] != 2:
        return False
    middle, i = c[1:-1], 0
    while i < len(middle):
        if middle[i] == 2:
            i += 1
        elif middle[i] == 1 and i + 1 < len(middle) and middle[i + 1] == 1:
            i += 2
        else:
            return False
    return True


def directives(p=4, q=5):
    """The cost of (n, m), m the label of p/q, for every n prime to m below m/2."""
    m = label(p, q)
    x = ((1, 0), (0, 1))
    for i in range(1, q + 1):
        x = mm(x, MU_B if (i * p) // q - ((i - 1) * p) // q else MU_A)
    root = min(x[0][0] % m, m - x[0][0] % m)
    pts = []
    for n in range(1, (m + 1) // 2):
        if 2 * n < m and gcd(n, m) == 1:
            c = continued_fraction(m, n)
            pts.append((n, sum(c) - 1, (n * n + 1) % m == 0, block_form(c)))
    least = min(cost for _, cost, _, _ in pts)
    roots = [(n, cost) for n, cost, sq, _ in pts if sq]
