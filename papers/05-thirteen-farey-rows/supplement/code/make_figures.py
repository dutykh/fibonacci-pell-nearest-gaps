"""Write the TikZ code of the figures of the article from exact data.

``figures/proof-map.tex``: the thirteen Farey rows against the denominator, with the
finite windows, the junctions and the unbounded tails.

``figures/norm-cloud.tex``: the normalized norms of all primitive pairs of one cost,
with the limits C_P of the normalized source labels of the rows.

``figures/parity-order.tex``: the normalized ratio of one-defect paths as a function of
a nonfinal gap and of the final gap.

``figures/junction.tex``: the normalized labels of the row of numerator eight around its
junction, against the band [C_8, U_8].

``figures/margins.tex``: for every occurrence with denominator at most 100, the cost of
the cheapest competing representation minus the occurrence cost.

``figures/thresholds.tex``: the margin against P + Q for every occurrence with P + Q at most
160 and margin at most 10, with the line (P + Q - 3)/24.

``figures/vieta-tree.tex``: the first four generations of the Farey tree, each fraction with its
label and the Gaussian integer given by the rule conj(alpha_M) = (m_L + i m_R)/alpha_D, started
from 1, 1 + i and 1 at 0/1, 1/1 and 1/0; every value is checked against the label of the
Christoffel word and against the occurrence pair of the central Gram factor.

``figures/directives.tex``: the Euclidean cost of the pair (n, 985) for every n prime to 985 with
n < 985/2, with the square roots of -1 and the integers whose continued fraction 985/n has the
form [2; B_1, ..., B_j, 2] with blocks (2) and (1,1).

All arithmetic is exact (integers, fractions, and decimal expansions of C_P to 60
digits); coordinates are rounded to three decimals of a centimetre only when written.
The margins figures read the census written by ``code/margins_census.gp`` (PARI/GP) and
re-verified by ``checks/independent_margins.py``; they are evidence for conjectures, not part
of a proof.  Run from the article folder:

    python3 -B supplement/code/make_figures.py
"""

