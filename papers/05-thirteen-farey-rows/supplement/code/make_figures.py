# Figure: the junction of the row of numerator eight.

def junction(qmax=81):
    c8 = c_const(8)
    u8 = dec(CEILINGS[8])
    pts = []
    for q in range(9, qmax + 1):
        if gcd(8, q) != 1:
            continue
        rho = Decimal(label(8, q)) / Decimal(fib(2 * (8 + q - 2) + 1))
        d = rho - c8
        assert d > 0
        pts.append((q, d, rho < u8))
    assert all(below == (q >= JUNCTIONS[8]) for q, _, below in pts)
    w, h = 12.0, 5.2
    lo_exp, hi_exp = -9.5, 0.0
    def X(q):
        return (q - 8) / (qmax + 1 - 8) * w
    def Y(d):
        return (math.log10(float(d)) - lo_exp) / (hi_exp - lo_exp) * h
    lines = [r"\begin{tikzpicture}[font=\footnotesize, >={Stealth[length=4pt]}]"]
    yu = Y(u8 - c8)
    lines.append(rf"\fill[sand] (0,0) rectangle ({fmt(w)},{fmt(yu)});")
    lines.append(rf"\draw[ochre, line width=0.8pt] (0,{fmt(yu)}) -- ({fmt(w)},{fmt(yu)});")
    lines.append(rf"\node[ochre, above left, font=\scriptsize] at ({fmt(w)},{fmt(yu)}) {{$U_8-C_8$}};")
    lines.append(rf"\node[slate, below left, font=\scriptsize, align=right] at ({fmt(w - 0.05)},{fmt(yu - 0.05)}) {{source band}};")
    xj = X(JUNCTIONS[8] - 1)            # 28 is not coprime to 8: the line separates window and tail
    lines.append(rf"\draw[slate, densely dashed, line width=0.6pt] ({fmt(xj)},0) -- ({fmt(xj)},{fmt(h)});")
    lines.append(rf"\node[wine, anchor=south east, font=\scriptsize] at ({fmt(xj - 0.05)},{fmt(h)}) {{finite window}};")
    lines.append(rf"\node[navy, anchor=south west, font=\scriptsize] at ({fmt(xj + 0.05)},{fmt(h)}) {{tail from $Q_8=29$}};")
    # the upper bound of the proposition on the labels of a row, C_8 (1 + phi^(-4n-6))^8 - C_8 with
    # n = floor((Q-8)/8), a staircase that lies above every label and enters the band at Q = 32
    def bound(n):
        return c8 * ((1 + PHI ** (-4 * n - 6)) ** 8 - 1)
    assert all(d < bound((q - 8) // 8) for q, d, _ in pts)
    assert bound(2) > u8 - c8 > bound(3)
    steps = []
    for n in range(0, (qmax - 8) // 8 + 1):
        qa, qb = max(9, 8 * (n + 1)), min(qmax + 0.5, 8 * (n + 2) - 0.5)
        steps.append((X(max(qa - 0.5, 8.5)), X(qb), Y(bound(n))))
    path = " -- ".join(f"({fmt(xa)},{fmt(y)}) -- ({fmt(xb)},{fmt(y)})" for xa, xb, y in steps)
    lines.append(rf"\draw[teal, line width=0.7pt, dash pattern=on 5pt off 2pt] {path};")
    xs = X(32)
    lines.append(rf"\draw[teal, line width=0.5pt] ({fmt(xs)},{fmt(Y(bound(3)) - 0.12)}) -- ({fmt(xs)},{fmt(Y(bound(3)) + 0.12)});")
    # label in the empty part of the band, right of the riser at Q = 56 and above the lower steps
    xl, yl0 = X(69), Y(bound(6)) + 0.68
    assert yl0 + 0.2 < yu - 0.35 and all(Y(bound(n)) < yl0 - 0.2 for n in range(6, 10))
    lines.append(rf"\node[teal, font=\scriptsize, inner sep=1pt] at ({fmt(xl)},{fmt(yl0)}) {{bound of \cref*{{prop:row-labels}}}};")
    for q, d, below in pts:
        colour = "navy" if below else "wine"
        lines.append(rf"\filldraw[{colour}, fill=white, line width=0.6pt] ({fmt(X(q))},{fmt(Y(d))}) circle (1.3pt);")
