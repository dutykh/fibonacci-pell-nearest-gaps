# Figure: the parity order for one defect.

def one_defect_ratio(g0, g1):
    x, y = 1, 2
    for _ in range(g0):
        x, y = y, x + y
    x, y = x, x + y
    for _ in range(g1):
        x, y = y, x + y
    cost = g0 + g1 + 2
    return Fraction(x * x + y * y, fib(2 * cost + 3))


def parity_order():
    """(a) |R - R_inf| along a nonfinal gap, log scale; (b) R along the final gap."""
    gmax = 12
    w, h = 5.2, 4.0
    r_inf = (15 - 3 * SQRT5) / 10          # exact value at g0 = infinity, final gap 0
    lines = [r"\begin{tikzpicture}[font=\footnotesize, >={Stealth[length=4pt]}]"]
    # panel (a)
    xoff = 0.0
    pts = [(g, dec(one_defect_ratio(g, 0)) - r_inf) for g in range(gmax + 1)]
    assert all((d < 0) == (g % 2 == 0) for g, d in pts)
    lo_e, hi_e = -7.0, -0.5
    def X(g):
        return xoff + (g + 0.6) / (gmax + 1.2) * w
    def Y(d):
        return (math.log10(abs(float(d))) - lo_e) / (hi_e - lo_e) * h
    assert all(lo_e < math.log10(abs(float(d))) < hi_e for _, d in pts)
    lines.append(rf"\node[ink, right] at ({fmt(xoff - 0.1)},{fmt(h + 0.45)}) {{(a) a nonfinal gap}};")
    lines.append(rf"\draw[ink, line width=0.5pt] ({fmt(xoff)},0) -- ({fmt(xoff + w)},0);")
    lines.append(rf"\draw[ink, line width=0.5pt] ({fmt(xoff)},0) -- ({fmt(xoff)},{fmt(h)});")
    for g in range(0, gmax + 1, 2):
        lines.append(rf"\draw[ink, line width=0.5pt] ({fmt(X(g))},0) -- ({fmt(X(g))},-0.08);")
        lines.append(rf"\node[ink, below] at ({fmt(X(g))},-0.08) {{${g}$}};")
    for e in range(-7, 0, 2):
        yy = (e - lo_e) / (hi_e - lo_e) * h
        lines.append(rf"\draw[ink, line width=0.5pt] ({fmt(xoff)},{fmt(yy)}) -- ({fmt(xoff - 0.08)},{fmt(yy)});")
        lines.append(rf"\node[ink, left] at ({fmt(xoff - 0.08)},{fmt(yy)}) {{$10^{{{e}}}$}};")
    lines.append(rf"\node[ink] at ({fmt(xoff + w / 2)},-0.75) {{nonfinal gap $g_0$}};")
    lines.append(rf"\node[ink, rotate=90] at ({fmt(xoff - 1.15)},{fmt(h / 2)}) {{distance to the limit}};")
    # both parities lie on one geometric line: a thin slate guide joins them in order
    path = " -- ".join(f"({fmt(X(g))},{fmt(Y(d))})" for g, d in pts)
    lines.append(rf"\draw[slate, line width=0.5pt] {path};")
    for parity, colour in ((0, "navy"), (1, "wine")):
        sel = [(g, d) for g, d in pts if g % 2 == parity]
        for g, d in sel:
            if parity == 0:
                lines.append(rf"\filldraw[{colour}, fill=white, line width=0.7pt] ({fmt(X(g))},{fmt(Y(d))}) circle (1.5pt);")
            else:
                lines.append(rf"\filldraw[{colour}, fill=white, line width=0.7pt] ({fmt(X(g) - 0.05)},{fmt(Y(d) - 0.05)}) rectangle ({fmt(X(g) + 0.05)},{fmt(Y(d) + 0.05)});")
    # legend of panel (a) in its empty upper right corner
    lx, ly = X(4.6), h - 0.25
    lines.append(rf"\filldraw[navy, fill=white, line width=0.7pt] ({fmt(lx + 0.2)},{fmt(ly)}) circle (1.5pt);")
    lines.append(rf"\node[navy, right, font=\scriptsize] at ({fmt(lx + 0.45)},{fmt(ly)}) {{even $g_0$: below the limit}};")
    lines.append(rf"\filldraw[wine, fill=white, line width=0.7pt] ({fmt(lx + 0.15)},{fmt(ly - 0.45)}) rectangle ({fmt(lx + 0.25)},{fmt(ly - 0.35)});")
    lines.append(rf"\node[wine, right, font=\scriptsize] at ({fmt(lx + 0.45)},{fmt(ly - 0.4)}) {{odd $g_0$: above the limit}};")
    # panel (b)
    xoff = 6.95
    series = [(g0, [(g1, one_defect_ratio(g0, g1)) for g1 in range(gmax + 1)]) for g0 in (2, 3)]
    values = [v for _, pts_b in series for _, v in pts_b]
    vlo, vhi = float(min(values)), float(max(values))
    pad = (vhi - vlo) * 0.08
    vlo, vhi = vlo - pad, vhi + pad
    def Xb(g):
        return xoff + (g + 0.6) / (gmax + 1.2) * w
    def Yb(v):
        return (float(v) - vlo) / (vhi - vlo) * h
    lines.append(rf"\node[ink, right] at ({fmt(xoff - 0.1)},{fmt(h + 0.45)}) {{(b) the final gap}};")
    lines.append(rf"\draw[ink, line width=0.5pt] ({fmt(xoff)},0) -- ({fmt(xoff + w)},0);")
    lines.append(rf"\draw[ink, line width=0.5pt] ({fmt(xoff)},0) -- ({fmt(xoff)},{fmt(h)});")
    for g in range(0, gmax + 1, 2):
        lines.append(rf"\draw[ink, line width=0.5pt] ({fmt(Xb(g))},0) -- ({fmt(Xb(g))},-0.08);")
        lines.append(rf"\node[ink, below] at ({fmt(Xb(g))},-0.08) {{${g}$}};")
    t = math.ceil(vlo / 0.01) * 0.01
    while t <= vhi:
        lines.append(rf"\draw[ink, line width=0.5pt] ({fmt(xoff)},{fmt(Yb(t))}) -- ({fmt(xoff - 0.08)},{fmt(Yb(t))});")
        lines.append(rf"\node[ink, left] at ({fmt(xoff - 0.08)},{fmt(Yb(t))}) {{${t:.2f}$}};")
        t += 0.01
    lines.append(rf"\node[ink] at ({fmt(xoff + w / 2)},-0.75) {{final gap $g_1$}};")
    for (g0, pts_b), colour, style in zip(series, ("navy", "wine"), ("", "densely dashed")):
        path = " -- ".join(f"({fmt(Xb(g))},{fmt(Yb(v))})" for g, v in pts_b)
        lines.append(rf"\draw[{colour}, line width=0.8pt, {style}] {path};")
    for (g0, pts_b), colour in zip(series, ("navy", "wine")):
        for g, v in pts_b:
            lines.append(rf"\filldraw[{colour}, fill=white, line width=0.6pt] ({fmt(Xb(g))},{fmt(Yb(v))}) circle (1.25pt);")
    lx, ly = Xb(6.0), h - 0.3
    for i, ((g0, _), colour, style) in enumerate(zip(series, ("navy", "wine"), ("", "densely dashed"))):
        yy = ly - 0.4 * i
        lines.append(rf"\draw[{colour}, line width=0.8pt, {style}] ({fmt(lx)},{fmt(yy)}) -- ({fmt(lx + 0.4)},{fmt(yy)});")
        lines.append(rf"\filldraw[{colour}, fill=white, line width=0.6pt] ({fmt(lx + 0.2)},{fmt(yy)}) circle (1.25pt);")
        lines.append(rf"\node[{colour}, right, font=\scriptsize] at ({fmt(lx + 0.45)},{fmt(yy)}) {{$g_0={g0}$}};")
    lines.append(rf"\node[ink, rotate=90] at ({fmt(xoff - 1.15)},{fmt(h / 2)}) {{$N/F_{{2c+3}}$}};")
    lines.append(r"\end{tikzpicture}")
    write("parity-order.tex", lines)


