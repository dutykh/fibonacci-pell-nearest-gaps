    lines.append(rf"\node[ink, rotate=90] at ({fmt(x0 - 1.0)},{fmt(h / 2)}) {{$\ell(n,985)$}};")
    lines.append(r"\end{tikzpicture}")
    write("directives.tex", lines)
    return len(pts), roots, blocks


