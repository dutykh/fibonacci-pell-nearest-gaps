# Figure: the first generations of the Farey tree with the Gaussian integers of the rule.

def gauss_div(a, b):
    """Exact quotient a/b of the Gaussian integers a = a0 + i a1 and b = b0 + i b1, given as pairs."""
    n = b[0] ** 2 + b[1] ** 2
    x, y = a[0] * b[0] + a[1] * b[1], a[1] * b[0] - a[0] * b[1]
    assert x % n == 0 and y % n == 0, (a, b)
    return (x // n, y // n)


def occurrence_pair(p, q):
    """The occurrence pair H e of the reduced fraction p/q, from the Gram factor of its central word."""
    word = "".join("b" if (i * p) // q - ((i - 1) * p) // q else "a" for i in range(1, q + 1))
    z = word[1:-1]
    n = len(z)
    h = ((1, 0), (0, 1))
    for c in z[(n + 1) // 2:]:
        h = mm(h, MU_A if c == "a" else MU_B)
    if n % 2:
        h = mm(((1, 1), (1, 0)) if z[n // 2] == "a" else ((2, 1), (1, 0)), h)
    return (2 * h[0][0] + h[0][1], 2 * h[1][0] + h[1][1])


def gauss_tex(a):
    """A Gaussian integer as TeX, for instance -5-3i, 1+i or 1."""
    x, y = a
    if y == 0:
        return str(x)
    coefficient = "" if abs(y) == 1 else str(abs(y))
    return f"{x}{'+' if y > 0 else '-'}{coefficient}i" if x else f"{'' if y > 0 else '-'}{coefficient}i"


def vieta_tree(depth=4):
    """The Farey tree to the given depth with the label and the Gaussian integer of each fraction."""
    start = {(0, 1): (0, 1, (1, 0)), (1, 1): (0, 2, (1, 1)), (1, 0): (0, 1, (1, 0))}
    nodes = {}
    def data(x):
        return start[x] if x in start else nodes[x][:3]
    def walk(left, right, diff, d):
        if d > depth:
            return
        mid = (left[0] + right[0], left[1] + right[1])
        (dl, ml, _), (dr, mr, _), (_, md, ad) = data(left), data(right), data(diff)
        mlab = 3 * ml * mr - md
        assert mlab == label(*mid)
        conj = gauss_div((ml, mr), ad)
        alpha = (conj[0], -conj[1])
        assert alpha[0] ** 2 + alpha[1] ** 2 == mlab
        assert sorted(map(abs, alpha)) == sorted(occurrence_pair(*mid))
        parents = [left, right] if dl == dr else [left if dl > dr else right]
        nodes[mid] = (d, mlab, alpha, parents)
        walk(left, mid, right, d + 1)
        walk(mid, right, left, d + 1)
    walk((0, 1), (1, 1), (1, 0), 1)
    assert nodes[(3, 5)][1:3] == (433, (17, -12)) and nodes[(1, 2)][2] == (1, -2)
    order = sorted(list(nodes) + [(0, 1), (1, 1)], key=lambda f: Fraction(*f))
    dx, dy = 0.84, 1.42
    def pos(f):
        if f == (1, 0):
            return (order.index((1, 2)) * dx, 0.0)
        level = 0 if f in start else nodes[f][0]
        return (order.index(f) * dx, -level * dy)
    def name(f):
        return f"f{f[0]}x{f[1]}"
    roles = {(1, 2): "L", (2, 3): "R", (1, 1): "D", (3, 5): "M"}
    styles = {"plain": "draw=mist, line width=0.5pt, fill=white",
              "start": "draw=slate, line width=0.5pt, dotted, fill=white",
              "LRD": "draw=wine, line width=0.9pt, fill=white",
              "M": "draw=navy, line width=1.1pt, fill=sand"}
    node_lines = []
    for f in [(0, 1), (1, 1), (1, 0)] + sorted(nodes, key=lambda f: (nodes[f][0], Fraction(*f))):
        x, y = pos(f)
        _, mlab, alpha = data(f)
        frac = f"{f[0]}/{f[1]}" if f not in roles else f"{roles[f]}={f[0]}/{f[1]}"
        if roles.get(f) == "M":
            style = styles["M"]
        elif f in roles:
            style = styles["LRD"]
        else:
            style = styles["start"] if f in start else styles["plain"]
        node_lines.append(rf"\node[{style}, rounded corners=1.5pt, inner sep=2pt, align=center] ({name(f)}) "
                          rf"at ({fmt(x)},{fmt(y)}) {{${frac}$\\${mlab}$\\${gauss_tex(alpha)}$}};")
    # each fraction is joined to its younger parent, and 1/2 to both; the edges of the
    # highlighted triangle and of its mediant 3/5 are drawn in colour instead
    highlighted = {frozenset({(1, 2), (2, 3)}), frozenset({(1, 2), (1, 1)})}
    edge_lines = sorted(rf"\draw[mist, line width=0.6pt] ({name(g)}) -- ({name(f)});"
                        for f, (_, _, _, parents) in nodes.items() for g in parents
                        if frozenset({f, g}) not in highlighted and f != (3, 5))
    for a, b in (((1, 2), (2, 3)), ((2, 3), (1, 1)), ((1, 1), (1, 2))):
        edge_lines.append(rf"\draw[wine, line width=0.8pt, dash pattern=on 3pt off 2pt] ({name(a)}) -- ({name(b)});")
    for a in ((1, 2), (2, 3)):
        edge_lines.append(rf"\draw[navy, line width=1.0pt] ({name(a)}) -- ({name((3, 5))});")
    # the nodes are drawn after the edges, so that their white fill hides the ends of the lines;
    # TikZ needs the node names before the edges use them, so the edges go on a background layer
    lines = [r"\begin{tikzpicture}[font=\scriptsize]"] + node_lines
    lines.append(r"\begin{scope}[on background layer]")
    lines += edge_lines
    lines.append(r"\end{scope}")
    lines.append(r"\end{tikzpicture}")
    write("vieta-tree.tex", lines)
    return {f: nodes[f][1:3] for f in nodes}


