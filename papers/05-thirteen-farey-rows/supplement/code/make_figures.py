SQRT5 = Decimal(5).sqrt()
PHI = (1 + SQRT5) / 2


def fmt(value):
    value = float(value)
    return f"{value:.3f}".rstrip("0").rstrip(".") if abs(value) >= 5e-4 else "0"


def fib(n):
    a, b = 0, 1
    for _ in range(n):
        a, b = b, a + b
    return a


def mm(x, y):
    return ((x[0][0]*y[0][0]+x[0][1]*y[1][0], x[0][0]*y[0][1]+x[0][1]*y[1][1]),
            (x[1][0]*y[0][0]+x[1][1]*y[1][0], x[1][0]*y[0][1]+x[1][1]*y[1][1]))


MU_A, MU_B = ((2, 1), (1, 1)), ((5, 2), (2, 1))


def label(p, q):
    """Markov label of the reduced fraction p/q from its lower Christoffel word."""
    x = ((1, 0), (0, 1))
    for i in range(1, q + 1):
        x = mm(x, MU_B if (i*p)//q - ((i-1)*p)//q else MU_A)
    assert x[0][0] + x[1][1] == 3 * x[0][1]
    return x[0][1]


def c_const(p):
    return PHI**2 * (3 / (SQRT5 * PHI))**(p - 1)


def dec(fr):
    return Decimal(fr.numerator) / Decimal(fr.denominator)


def write(name, lines):
    path = ROOT / "figures" / name
    path.write_text(HEADER + "\n".join(lines) + "\n")
    print("wrote", path.relative_to(ROOT))


